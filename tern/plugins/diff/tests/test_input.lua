local source = debug.getinfo(1, "S").source:sub(2)
local Input = dofile(source:match("^(.*[/\\])") .. "../input.luau")
local field = Input.new("a😀éz")
assert(field.cursor == 5)
Input.key(field, { name = "left" })
assert(field.cursor == 4)
Input.key(field, { name = "left" })
assert(field.cursor == 3)
Input.key(field, { name = "backspace" })
assert(field.text == "aéz" and field.cursor == 1)
Input.key(field, { name = "delete" })
assert(field.text == "az" and field.cursor == 1)
Input.edit(field, 1, 2, "界😀", 4)
assert(field.text == "a界😀" and field.cursor == 4)
Input.key(field, { name = "home" })
Input.key(field, { name = "backspace" })
assert(field.text == "a界😀" and field.cursor == 0)
Input.key(field, { name = "end" })
Input.key(field, { name = "delete" })
assert(field.text == "a界😀" and field.cursor == 4)
Input.edit(field, 2, 4, "x\ny", 5)
assert(field.text == "a界x y" and field.cursor == 5)
field = Input.new("one  two three")
Input.key(field, { name = "w", ctrl = true })
assert(field.text == "one  two ")
Input.key(field, { name = "u", ctrl = true })
assert(field.text == "" and field.cursor == 0)
print("Unicode codepoint deletion, UTF-16 replacement, edge cursors, newline sanitation and word deletion passed")
